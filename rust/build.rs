//! Generates the icon table from the repository's `svg-bare/` directory.
//!
//! The crate is used both from this repository and as a Git dependency.
//! In both cases the parent directory contains the SVG library, so this build
//! script never performs network I/O.
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let svg_dir = env::var_os("UUHONK_ICONS_SVG_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../svg-bare"));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=UUHONK_ICONS_SVG_DIR");
    println!("cargo:rerun-if-changed={}", svg_dir.display());

    let mut files = Vec::new();
    for entry in fs::read_dir(&svg_dir)
        .unwrap_or_else(|error| panic!("cannot read icon directory {}: {error}", svg_dir.display()))
    {
        let path = entry.expect("icon entry").path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("svg") {
            continue;
        }
        let Some(name) = path.file_stem().and_then(|name| name.to_str()) else {
            continue;
        };
        let svg = fs::read_to_string(&path).expect("read SVG");
        files.push((name.to_owned(), svg.trim().to_owned()));
    }
    files.sort_by(|left, right| left.0.cmp(&right.0));
    assert!(!files.is_empty(), "no SVG files in {}", svg_dir.display());

    let mut constants = String::new();
    let mut definitions = String::new();
    for (name, svg) in files {
        let ident = constant(&name);
        constants.push_str(&format!(
            "pub const {ident}: &str = {};\n",
            raw_string(&svg)
        ));
        definitions.push_str(&format!(
            "    Icon {{\n        name: \"{name}\",\n        svg: {ident},\n    }},\n"
        ));
    }
    let generated = format!(
        "// @generated by rust/build.rs; do not edit by hand.\n\n{constants}\n\
         pub static ICONS: &[Icon] = &[\n{definitions}];\n"
    );
    let out = Path::new(&env::var_os("OUT_DIR").expect("OUT_DIR")).join("icons.rs");
    fs::write(out, generated).expect("write generated icons");
}

fn raw_string(svg: &str) -> String {
    let mut hashes = 3;
    while svg.contains(&"#".repeat(hashes)) {
        hashes += 1;
    }
    let marker = "#".repeat(hashes);
    format!("r{marker}\"{svg}\"{marker}")
}

fn constant(name: &str) -> String {
    name.chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch } else { '_' })
        .collect::<String>()
        .to_ascii_uppercase()
}
